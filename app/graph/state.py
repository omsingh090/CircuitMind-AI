"""Typed State Structure for CircuitMind AI LangGraph Agentic Workflow.

Defines the shared state blackboard across all specialized electronics engineering agents:
- Requirement Agent
- Research Agent (Hybrid RAG)
- Component Agent
- Validation Agent (Deterministic Safety)
- Report Agent
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, TypedDict
from pydantic import BaseModel, Field


class ExtractedRequirements(BaseModel):
    """Structured engineering design requirements extracted from user query."""

    target_components: List[str] = Field(default_factory=list, description="Identified component part numbers (e.g., LM35)")
    target_supply_voltage_v: Optional[float] = Field(default=None, description="Operating supply voltage in Volts")
    target_max_current_ma: Optional[float] = Field(default=None, description="Operating/maximum current target in mA")
    min_temp_c: Optional[float] = Field(default=None, description="Minimum operational temperature target in °C")
    max_temp_c: Optional[float] = Field(default=None, description="Maximum operational temperature target in °C")
    adc_reference_voltage_v: Optional[float] = Field(default=None, description="ADC reference or input full-scale voltage in Volts")
    load_impedance_ohms: Optional[float] = Field(default=None, description="Load resistance or impedance in Ohms")
    identified_requirements: Dict[str, Any] = Field(default_factory=dict, description="Key-value dictionary of stated requirements")
    missing_requirements: List[str] = Field(default_factory=list, description="Explicitly identified unstated engineering parameters")


class ComponentSpecification(BaseModel):
    """Verified electrical component specification with source datasheet citation and metadata."""

    parameter: str = Field(description="Parameter name (e.g. Recommended Supply Voltage)")
    value: Any = Field(description="Parameter value or range (e.g. 4V to 30V)")
    unit: Optional[str] = Field(default=None, description="Physical unit (e.g. V, mA, mV/°C)")
    status: str = Field(default="typical", description="Specification status: typical, minimum, maximum, guaranteed, recommended_operating, absolute_maximum")
    conditions: Optional[str] = Field(default=None, description="Applicable operating temperature and voltage conditions")
    variant: Optional[str] = Field(default=None, description="Applicable component variant (e.g. LM35, LM35A)")
    source: str = Field(description="Datasheet source filename")
    page: Any = Field(description="Page number in source datasheet")
    citation: Optional[str] = Field(default=None, description="Formatted citation string e.g. [lm35.pdf, p. 1]")
    notes: Optional[str] = Field(default=None, description="Additional conditions or limits")


class ComponentInformation(BaseModel):
    """Extracted component specifications and missing parameters."""

    part_number: str = Field(description="Component identifier")
    verified_specs: Dict[str, Any] = Field(default_factory=dict, description="Verified datasheet specifications")
    unverified_or_missing_specs: List[str] = Field(default_factory=list, description="Specifications not found in datasheet evidence")
    citations: List[Dict[str, Any]] = Field(default_factory=list, description="Source datasheet citations")


class ValidationResults(BaseModel):
    """Deterministic electrical safety and compatibility validation results."""

    status: str = Field(
        default="INCONCLUSIVE",
        description="Explicit validation status: 'VALID', 'INVALID', or 'INCONCLUSIVE'",
    )
    is_valid: bool = Field(default=False, description="Whether design passed all required electrical safety checks")
    checks: List[Dict[str, Any]] = Field(default_factory=list, description="Individual electrical check results")
    violations: List[str] = Field(default_factory=list, description="Critical electrical violations")
    warnings: List[str] = Field(default_factory=list, description="Engineering warnings and derating notices")
    calculations: Dict[str, Any] = Field(default_factory=dict, description="Deterministic calculations performed")


class EngineeringReport(BaseModel):
    """Comprehensive structured engineering report generated by CircuitMind AI."""

    title: str = Field(description="Report title")
    executive_summary: str = Field(description="High-level engineering evaluation summary")
    requirements_summary: str = Field(description="Summary of provided and missing requirements")
    component_specifications: str = Field(description="Verified component specifications with citations")
    validation_summary: str = Field(description="Deterministic electrical validation results")
    warnings_and_limitations: List[str] = Field(default_factory=list, description="Design limitations and warnings")
    citations: List[Dict[str, Any]] = Field(default_factory=list, description="Datasheet citations")
    fabrication_disclaimer: str = Field(
        default="PRELIMINARY COPILOT DESIGN: This analysis is an engineering recommendation. "
                "It is not fabrication-ready without formal schematic capture, physical prototype testing, "
                "and peer review.",
        description="Mandatory engineering integrity disclaimer"
    )


class CircuitMindState(TypedDict, total=False):
    """LangGraph shared workflow state structure.

    Attributes:
        user_query: The raw engineering prompt provided by the user.
        requirements: Extracted user design requirements and missing inputs.
        retrieved_documents: Raw datasheet text chunks and metadata retrieved via hybrid RAG.
        component_information: Verified component specifications with citations and missing specs.
        validation_results: Deterministic electrical safety checks and calculations.
        engineering_report: Final synthesized structured engineering report.
        errors: List of non-fatal errors or warnings accumulated across workflow nodes.
    """

    user_query: str
    requirements: Dict[str, Any]
    retrieved_documents: List[Dict[str, Any]]
    component_information: Dict[str, Any]
    validation_results: Dict[str, Any]
    engineering_report: Dict[str, Any]
    node_execution_times: Dict[str, float]
    errors: List[str]

